package com.asterdoc.app.pdf;

import android.content.Context;
import android.graphics.Canvas;
import android.graphics.Color;
import android.graphics.Paint;
import android.graphics.pdf.PdfDocument;

import java.io.File;
import java.io.FileOutputStream;
import java.text.DateFormat;
import java.util.Date;

public class SamplePdfGenerator {

    public static File createSamplePdf(Context context, String fileName, String docTitle) {
        File dir = context.getExternalFilesDir("Documents");
        if (dir != null && !dir.exists()) dir.mkdirs();

        File outputFile = new File(dir, fileName.endsWith(".pdf") ? fileName : fileName + ".pdf");
        if (outputFile.exists() && outputFile.length() > 0) {
            return outputFile;
        }

        try {
            PdfDocument document = new PdfDocument();

            // Page 1
            PdfDocument.PageInfo pageInfo1 = new PdfDocument.PageInfo.Builder(595, 842, 1).create(); // A4 size
            PdfDocument.Page page1 = document.startPage(pageInfo1);
            Canvas canvas1 = page1.getCanvas();

            Paint headerPaint = new Paint();
            headerPaint.setColor(0xFF1A73E8); // Primary Blue
            canvas1.drawRect(0, 0, 595, 100, headerPaint);

            Paint headerTextPaint = new Paint();
            headerTextPaint.setColor(Color.WHITE);
            headerTextPaint.setTextSize(24f);
            headerTextPaint.setFakeBoldText(true);
            canvas1.drawText("AsterDocs — Document Reader", 40, 58, headerTextPaint);

            Paint titlePaint = new Paint();
            titlePaint.setColor(0xFF202124);
            titlePaint.setTextSize(20f);
            titlePaint.setFakeBoldText(true);
            canvas1.drawText(docTitle, 40, 150, titlePaint);

            Paint bodyPaint = new Paint();
            bodyPaint.setColor(0xFF5F6368);
            bodyPaint.setTextSize(14f);

            int y = 190;
            canvas1.drawText("This is an official document generated by AsterDocs.", 40, y, bodyPaint); y += 28;
            canvas1.drawText("Date: " + DateFormat.getDateInstance().format(new Date()), 40, y, bodyPaint); y += 28;
            canvas1.drawText("File Name: " + fileName, 40, y, bodyPaint); y += 40;

            Paint dividerPaint = new Paint();
            dividerPaint.setColor(0xFFE0E0E0);
            dividerPaint.setStrokeWidth(2f);
            canvas1.drawLine(40, y, 555, y, dividerPaint); y += 40;

            canvas1.drawText("1. OVERVIEW", 40, y, titlePaint); y += 28;
            canvas1.drawText("AsterDocs provides seamless PDF creation, editing, scanning, compression,", 40, y, bodyPaint); y += 22;
            canvas1.drawText("merging, splitting, signing, and OCR text recognition directly on Android.", 40, y, bodyPaint); y += 40;

            canvas1.drawText("2. SECURITY & PRIVACY", 40, y, titlePaint); y += 28;
            canvas1.drawText("All processing is performed locally on your device with 256-bit encryption.", 40, y, bodyPaint); y += 22;
            canvas1.drawText("Your private files remain securely in your control at all times.", 40, y, bodyPaint); y += 60;

            Paint footerPaint = new Paint();
            footerPaint.setColor(0xFF1A73E8);
            footerPaint.setTextSize(12f);
            canvas1.drawText("Page 1 of 2 • Confidential Document", 40, 800, footerPaint);

            document.finishPage(page1);

            // Page 2
            PdfDocument.PageInfo pageInfo2 = new PdfDocument.PageInfo.Builder(595, 842, 2).create();
            PdfDocument.Page page2 = document.startPage(pageInfo2);
            Canvas canvas2 = page2.getCanvas();

            canvas2.drawRect(0, 0, 595, 100, headerPaint);
            canvas2.drawText("AsterDocs — Document Reader", 40, 58, headerTextPaint);

            y = 150;
            canvas2.drawText("3. VERIFICATION & SUMMARY", 40, y, titlePaint); y += 28;
            canvas2.drawText("This document confirms that AsterDocs PDF rendering engine is fully operational.", 40, y, bodyPaint); y += 22;
            canvas2.drawText("You can read, navigate pages, share, and export your files instantly.", 40, y, bodyPaint); y += 50;

            canvas2.drawText("Authorized Signature:", 40, y, bodyPaint); y += 30;
            Paint sigPaint = new Paint();
            sigPaint.setColor(0xFF1A73E8);
            sigPaint.setTextSize(18f);
            sigPaint.setFakeBoldText(true);
            canvas2.drawText("AsterDocs Verified ✓", 40, y, sigPaint);

            canvas2.drawText("Page 2 of 2 • Confidential Document", 40, 800, footerPaint);
            document.finishPage(page2);

            FileOutputStream fos = new FileOutputStream(outputFile);
            document.writeTo(fos);
            fos.close();
            document.close();

            return outputFile;
        } catch (Exception e) {
            return outputFile;
        }
    }
}
